export function t(lang, key) {
  const v = LANG[lang]?.[key];
  return v !== undefined ? v : LANG.en[key];
}

// t() with {placeholder} substitution: fill(lang, "promptAddLoad", { w: 60, kg: 2.5 })
export function fill(lang, key, vals = {}) {
  return String(t(lang, key)).replace(/\{(\w+)\}/g, (_, k) => (vals[k] !== undefined ? String(vals[k]) : `{${k}}`));
}
